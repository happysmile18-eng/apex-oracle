def _merge_result_pages(pages: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Merge paginated Jolpica results without splitting one race into fake races."""
    merged: dict[tuple[int, int], dict[str, Any]] = {}
    seen_drivers: dict[tuple[int, int], set[str]] = defaultdict(set)

    for payload in pages:
        races = payload.get("MRData", {}).get("RaceTable", {}).get("Races", [])
        for race in races:
            season = safe_int(race.get("season"))
            round_no = safe_int(race.get("round"))
            key = (season, round_no)
            if key not in merged:
                merged[key] = dict(race)
                merged[key]["Results"] = []
            for result in race.get("Results", []):
                driver_id = result.get("Driver", {}).get("driverId") or f"position-{result.get('position')}"
                if driver_id in seen_drivers[key]:
                    continue
                seen_drivers[key].add(driver_id)
                merged[key]["Results"].append(result)

    races = list(merged.values())
    for race in races:
        race["Results"].sort(key=lambda result: safe_int(result.get("position"), 999))
    races.sort(key=lambda race: (safe_int(race.get("season")), safe_int(race.get("round"))))
    return races


@st.cache_data(ttl=60 * 60 * 2, show_spinner=False, max_entries=24)
def fetch_results(season: int) -> list[dict[str, Any]]:
    """Fetch completed races one round at a time.

    Per-round calls are slower than one giant season query, but much more robust:
    a race is never split across pagination pages and one failed round does not
    invalidate the whole season. This function is only used to refresh the
    bundled archive with the newest completed races.
    """
    try:
        schedule = fetch_schedule(season)
    except DataError:
        return []

    now = datetime.now(timezone.utc)
    completed_candidates = [
        race for race in schedule
        if race_datetime(race) <= now - timedelta(minutes=75)
    ]
    races: list[dict[str, Any]] = []
    for race in completed_candidates:
        round_no = safe_int(race.get("round"))
        if round_no <= 0:
            continue
        try:
            payload = jolpica_get(f"{season}/{round_no}/results.json?limit=100")
        except DataError:
            continue
        returned = payload.get("MRData", {}).get("RaceTable", {}).get("Races", [])
        if returned and len(returned[0].get("Results", [])) >= 10:
            races.append(returned[0])
    races.sort(key=lambda race: safe_int(race.get("round")))
    return races


