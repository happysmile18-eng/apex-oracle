@st.cache_data(ttl=60 * 60 * 2, show_spinner=False)
def load_history(start_season: int, current_season: int) -> list[dict[str, Any]]:
    """Load guaranteed local history, then merge any newer live results.

    The model no longer depends on Jolpica for its training base. Network data
    can improve freshness, but an outage cannot reduce the archive below the
    minimum needed to train.
    """
    merged: dict[tuple[int, int], dict[str, Any]] = {}
    for race in load_embedded_history():
        year = safe_int(race.get("season"))
        if start_season <= year <= current_season and len(race.get("Results", [])) >= 10:
            merged[(year, safe_int(race.get("round")))] = race

    # Best-effort live refresh for the current season. Any API problem is ignored
    # because the local archive remains a complete and valid training source.
    try:
        for race in fetch_results(current_season):
            if len(race.get("Results", [])) >= 10:
                copy = dict(race)
                copy["season"] = str(current_season)
                merged[(current_season, safe_int(copy.get("round")))] = copy
    except Exception:
        pass

    races = list(merged.values())
    races.sort(key=lambda r: (safe_int(r.get("season")), safe_int(r.get("round"))))
    return races


